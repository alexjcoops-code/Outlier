// Copies the game's pure logic into supabase/functions/_shared/core so the Edge
// Functions use exactly the same prompts, validators and ghost rules as the app.
// Supabase only bundles files under supabase/functions, hence the copy.
//
//   npm run sync:shared          copy
//   npm run sync:shared -- --check   exit 1 if the copies are stale (used in tests/CI)

import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(root, 'supabase/functions/_shared/core');

export const SHARED_FILES = [
  'prompts.ts',
  'lib/maths.ts',
  'lib/rng.ts',
  'lib/ukDate.ts',
  'lib/daily.ts',
  'lib/ghostConfig.ts',
  'lib/ghostModel.ts',
  'lib/ghostAi.ts',
  'lib/scoring.ts',
  'lib/versus.ts',
];

const BANNER = '// GENERATED by scripts/sync-shared.mjs from src/. Do not edit: change src/ and run `npm run sync:shared`.\n';

const check = process.argv.includes('--check');
let stale = 0;
for (const file of SHARED_FILES) {
  const wanted = BANNER + readFileSync(join(root, 'src', file), 'utf8');
  const dest = join(target, file);
  const current = existsSync(dest) ? readFileSync(dest, 'utf8') : null;
  if (current === wanted) continue;
  stale++;
  if (check) {
    console.error(`stale: supabase/functions/_shared/core/${file}`);
  } else {
    mkdirSync(dirname(dest), { recursive: true });
    writeFileSync(dest, wanted);
    console.log(`synced ${file}`);
  }
}
if (check && stale) {
  console.error('Run `npm run sync:shared`.');
  process.exit(1);
}
if (!check && !stale) console.log('Shared code already up to date.');
