// Writes docs/questions.md: every question in the bank, grouped by type, with
// its difficulty, how many right answers it has and a few of them.
//
//   npm run questions          rewrite the file
//   npm run questions -- --check   exit 1 if the file is out of date (used in tests)

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { FAMILIES, validAnswers } from '../src/prompts.ts';

const OUT = new URL('../docs/questions.md', import.meta.url);
const LABEL = { 1: 'easy', 2: 'medium', 3: 'hard' } as const;

function render(): string {
  const lines: string[] = [
    '# Oddle question bank',
    '',
    '<!-- GENERATED by scripts/list-questions.ts. Do not edit: run `npm run questions`. -->',
    '',
    `${FAMILIES.length} question types, ${FAMILIES.reduce((n, f) => n + f.prompts.length, 0)} questions. ` +
      'A type never appears twice within 3 days, and a question never repeats within 60 days.',
    '',
  ];
  for (const fam of FAMILIES) {
    lines.push(`## ${fam.name} \`${fam.id}\``, '', '| # | Question | Level | Answers | e.g. |', '|---|---|---|---|---|');
    for (const p of fam.prompts) {
      const all = validAnswers(p);
      const pick = [all[0], all[Math.floor(all.length / 2)], all[all.length - 1]].filter((x, i, a) => x !== undefined && a.indexOf(x) === i);
      lines.push(`| ${p.id.slice(-2)} | ${p.text.replace(/\|/g, '\\|')} | ${LABEL[p.difficulty]} | ${all.length.toLocaleString('en-GB')} | ${pick.join(', ')} |`);
    }
    lines.push('');
  }
  return lines.join('\n');
}

const wanted = render();
if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== wanted) {
    console.error('docs/questions.md is out of date: run `npm run questions`');
    process.exit(1);
  }
} else {
  writeFileSync(OUT, wanted);
  console.log('wrote docs/questions.md');
}
